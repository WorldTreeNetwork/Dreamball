//! Story 1.1 — Codegen Inversion Spike (JSON-Schema consumer).
//!
//! Reads the three hand-authored JSON Schemas under
//! `tools/schema-gen/spike/schemas/` (envelope, sealed-body,
//! signature-tier-wrapper) and emits Zig + TS + Valibot + CBOR codec stubs
//! byte-equivalent to the snippets the legacy `tools/schema-gen/main.zig`
//! produces for the same three types (snapshotted in
//! `tools/schema-gen/legacy-spike-fixture/`).
//!
//! Per D-018: this consumer does NOT re-author CBOR encoding semantics.
//! It emits the three TAG_* constants the legacy generator emits and
//! defers the actual encoding/decoding to the canonical Zig CBOR rules
//! that already live in `src/dcbor.zig` + `src/envelope*.zig`.
//!
//! Per AC2: byte-equivalence is the gating constraint.
//! `diff -r tools/schema-gen/spike/out/ tools/schema-gen/legacy-spike-fixture/`
//! MUST be empty.
//!
//! Per AC3: each construct that JSON Schema 2020-12 cannot natively
//! express (discriminated unions over `type`, the `${DreamBallType}`
//! template-string variant, the SignatureTierWrapper as an attribute-pair
//! 2-array rather than an object) is recorded in
//! `docs/decisions/2026-04-28-codegen-spike-findings.md` with the chosen
//! normalization.
//!
//! Run: `zig build schemagen-spike`. NFR2 budget: ≤ 5 s wall clock.
//! Time externally with `time zig build schemagen-spike` per the spike
//! findings doc; the consumer itself just reports "done".

